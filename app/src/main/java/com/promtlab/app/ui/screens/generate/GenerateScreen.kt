    icon: ImageVector,
    contentDescription: String,
    onClick: () -> Unit
) {
    val cs = MaterialTheme.colorScheme
    Box(
        modifier = Modifier
            .size(54.dp)
            .clip(RoundedCornerShape(18.dp))
            .background(cs.surfaceContainerHigh)
            .clickable(onClick = onClick),
        contentAlignment = Alignment.Center
    ) {
        Icon(
            imageVector = icon,
            contentDescription = contentDescription,
            tint = cs.primary,
            modifier = Modifier.size(22.dp)
        )
    }
}

@Composable
private fun SavePromptDialog(
    defaultTitle: String,
    onDismiss: () -> Unit,
    onConfirm: (String, PromptCategory) -> Unit
) {
    var title by remember { mutableStateOf(defaultTitle) }
    var category by remember { mutableStateOf(PromptCategory.WRITING) }
    val cs = MaterialTheme.colorScheme

    AlertDialog(
        onDismissRequest = onDismiss,
        shape = RoundedCornerShape(26.dp),
        containerColor = cs.surfaceContainerHigh,
        title = { Text("Сохранить промт") },
        text = {
            Column(verticalArrangement = Arrangement.spacedBy(12.dp)) {
                OutlinedTextField(
                    value = title,
                    onValueChange = { title = it },
                    label = { Text("Название") },
                    singleLine = true,
                    shape = RoundedCornerShape(14.dp),
                    modifier = Modifier.fillMaxWidth()
                )
                FieldLabel("КАТЕГОРИЯ")
                ChoiceChips(
                    options = PromptCategory.entries,
                    selected = category,
                    label = { it.label },
                    onSelect = { category = it }
                )
            }
        },
        confirmButton = {
            TextButton(onClick = { onConfirm(title, category) }) {
                Text("Сохранить")
            }
        },
        dismissButton = {
            TextButton(onClick = onDismiss) {
                Text("Отмена")
            }
        }
    )
}

/* ------------------------------ Утилиты формы ---------------------------- */

private fun toggle(set: Set<Technique>, technique: Technique): Set<Technique> =
    if (technique in set) set - technique else set + technique

private fun appendConstraint(current: String, constraint: String): String {
    if (current.contains(constraint, ignoreCase = true)) return current
    return when {
        current.isBlank() -> constraint
        current.trimEnd().endsWith(",") -> "$current $constraint"
        else -> "${current.trimEnd()}, $constraint"
    }
}
