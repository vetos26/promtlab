    )
    LazyRow(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
        items(roles) { role ->
            AssistChip(
                onClick = { onPick("$role с опытом 10+ лет") },
                label = {
                    Text(text = role, style = MaterialTheme.typography.labelSmall)
                },
                shape = RoundedCornerShape(12.dp)
            )
        }
    }
}

