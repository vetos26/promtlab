@Composable
private fun PresetsRow(onPick: (ImagePromptForm) -> Unit) {
    LazyRow(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
        items(ImagePromptGenerator.presets) { preset ->
            AssistChip(
                onClick = { onPick(preset.form) },
                label = {
                    Text(text = preset.title, style = MaterialTheme.typography.labelSmall)
                },
                shape = RoundedCornerShape(12.dp)
            )
        }
    }
}

@Composable
private fun NegativeSuggestions(onPick: (String) -> Unit) {
    val words = listOf("watermark", "text", "blurry", "extra fingers", "logo", "low contrast")
    LazyRow(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
        items(words) { word ->
            AssistChip(
                onClick = { onPick(word) },
                label = {
                    Text(text = "+ $word", style = MaterialTheme.typography.labelSmall)
                },
                shape = RoundedCornerShape(12.dp)
            )
        }
    }
}

@Composable
private fun FieldLabel(text: String) {
    Text(
        text = text,
        style = MaterialTheme.typography.labelSmall,
        color = MaterialTheme.colorScheme.onSurfaceVariant,
        letterSpacing = 0.8.sp
    )
}

@Composable
private fun ImagePreviewCard(
    form: ImagePromptForm,
    english: String,
    negative: String,
    parameters: String,
    tokens: Int,
    score: Int,
    expanded: Boolean,
    onToggleExpanded: () -> Unit,
    onCopy: () -> Unit,
    onShare: () -> Unit,
    onSave: () -> Unit
) {
    val cs = MaterialTheme.colorScheme
    SectionCard(title = "Готовый промт", icon = Icons.Rounded.Image) {
        Row(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
            InfoPill(text = form.target.shortLabel)
            InfoPill(text = form.aspect.label, tint = cs.secondary)
            InfoPill(text = "≈$tokens токенов", tint = cs.tertiary)
        }

        PromptBlock(title = "PROMPT", text = english, expanded = expanded)
        if (negative.isNotBlank()) {
            PromptBlock(
                title = "NEGATIVE",
                text = negative,
                expanded = expanded,
                maxCollapsedLines = 3
            )
        }
        PromptBlock(title = "ПАРАМЕТРЫ", text = parameters, expanded = true)

        TextButton(onClick = onToggleExpanded) {
            Text(
                text = if (expanded) "Свернуть" else "Показать полностью",
                style = MaterialTheme.typography.labelLarge
            )
        }

        Row(
            horizontalArrangement = Arrangement.spacedBy(8.dp),
            verticalAlignment = Alignment.CenterVertically
        ) {
            GradientButton(
                text = "Копировать",
                onClick = onCopy,
                icon = Icons.Rounded.ContentCopy,
                modifier = Modifier.weight(1f)
            )
            CircleActionButton(
                icon = Icons.Rounded.Share,
                contentDescription = "Поделиться промтом",
                onClick = onShare
            )
            CircleActionButton(
                icon = Icons.Rounded.BookmarkAdd,
                contentDescription = "Сохранить в историю",
                onClick = onSave
            )
        }

        Text(
            text = "Стиль: ${form.style.label} · Свет: ${form.lighting.label} · Оценка: $score%",
            style = MaterialTheme.typography.bodySmall,
            color = cs.onSurfaceVariant
        )
    }
}

@Composable
private fun PromptBlock(
    title: String,
    text: String,
    expanded: Boolean,
    maxCollapsedLines: Int = 8
) {
    val cs = MaterialTheme.colorScheme
    Column(verticalArrangement = Arrangement.spacedBy(4.dp)) {
        Text(
            text = title,
            style = MaterialTheme.typography.labelSmall,
            color = cs.primary,
            letterSpacing = 0.8.sp
        )
        Surface(
            modifier = Modifier.fillMaxWidth(),
            shape = RoundedCornerShape(16.dp),
            color = cs.surfaceContainerHighest.copy(alpha = 0.45f),
            border = BorderStroke(1.dp, cs.outlineVariant.copy(alpha = 0.6f))
        ) {
            Text(
                text = text,
                modifier = Modifier
                    .fillMaxWidth()
                    .padding(12.dp),
                style = MaterialTheme.typography.bodySmall.copy(
                    fontFamily = FontFamily.Monospace,
                    lineHeight = 18.sp
                ),
                color = cs.onSurface,
                maxLines = if (expanded) Int.MAX_VALUE else maxCollapsedLines,
                overflow = TextOverflow.Ellipsis
            )
        }
    }
}

private fun appendNegative(current: String, word: String): String {
    if (current.contains(word, ignoreCase = true)) return current
    return when {
        current.isBlank() -> word
        current.trimEnd().endsWith(",") -> "$current $word"
        else -> "${current.trimEnd()}, $word"
    }
}
