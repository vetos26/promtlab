/**
 * Режим «Изображение» внутри генератора: промты для Midjourney,
 * Stable Diffusion, DALL·E и Flux с негативным промтом и параметрами.
 */
@Composable
fun ImagePromptPane(
    viewModel: AppViewModel,
    modifier: Modifier = Modifier
) {
    val form by viewModel.imageForm.collectAsStateWithLifecycle()
    val generated by viewModel.generatedImage.collectAsStateWithLifecycle()
    val context = LocalContext.current

    var showSaveDialog by remember { mutableStateOf(false) }
    var previewExpanded by remember { mutableStateOf(false) }

    if (showSaveDialog) {
        SavePromptDialog(
            defaultTitle = titleFromPrompt(generated.english),
            defaultCategory = PromptCategory.DESIGN,
            onDismiss = { showSaveDialog = false },
            onConfirm = { title, _ ->
                viewModel.saveImagePrompt(title)
                showSaveDialog = false
            }
        )
    }

    LazyColumn(
        modifier = modifier.fillMaxSize(),
        contentPadding = PaddingValues(start = 20.dp, end = 20.dp, top = 12.dp, bottom = 28.dp),
        verticalArrangement = Arrangement.spacedBy(16.dp)
    ) {
        item {
            QualityCard(
                score = generated.score,
                hints = generated.hints,
                title = "Качество промта изображения",
                icon = Icons.Rounded.Image
            )
        }

        item {
            PresetsRow(
                onPick = { presetForm ->
                    viewModel.updateImageForm { presetForm }
                    viewModel.showMessage("Идея для изображения подставлена")
                }
            )
        }

        item {
            SectionCard(title = "Что на изображении", icon = Icons.Rounded.Image) {
                Text(
                    text = "Главный объект — в первых словах промта: они весят больше всего.",
                    style = MaterialTheme.typography.bodySmall,
                    color = MaterialTheme.colorScheme.onSurfaceVariant
                )
                LabeledField(
                    label = "Сюжет (можно по-русски)",
                    value = form.subject,
                    onValueChange = { value ->
                        viewModel.updateImageForm { current -> current.copy(subject = value) }
                    },
                    placeholder = "Например: дождливая улица киберпанк-города, курьер с неоновым зонтом",
                    minLines = 2,
                    maxLines = 5
                )
                LabeledField(
                    label = "Детали и окружение",
                    value = form.details,
                    onValueChange = { value ->
                        viewModel.updateImageForm { current -> current.copy(details = value) }
                    },
                    placeholder = "Материалы, время суток, реквизит, отражения…",
                    minLines = 2,
                    maxLines = 5
                )
            }
        }

        item {
            SectionCard(title = "Стиль и палитра", icon = Icons.Rounded.Palette) {
                FieldLabel("СТИЛЬ")
                ChoiceChips(
                    options = ImageStyle.entries,
                    selected = form.style,
                    label = { "${it.emoji} ${it.label}" },
                    onSelect = { style ->
                        viewModel.updateImageForm { current -> current.copy(style = style) }
                    }
                )
                FieldLabel("ЦВЕТОВАЯ ПАЛИТРА")
                ChoiceChips(
                    options = ColorPalette.entries,
                    selected = form.palette,
                    label = { it.label },
                    onSelect = { palette ->
                        viewModel.updateImageForm { current -> current.copy(palette = palette) }
                    }
                )
            }
        }

        item {
            SectionCard(title = "Свет, кадр и настроение", icon = Icons.Rounded.LightMode) {
                FieldLabel("ОСВЕЩЕНИЕ")
                ChoiceChips(
                    options = ImageLighting.entries,
                    selected = form.lighting,
                    label = { it.label },
                    onSelect = { lighting ->
                        viewModel.updateImageForm { current -> current.copy(lighting = lighting) }
                    }
                )
                FieldLabel("КАДР")
                ChoiceChips(
                    options = CameraShot.entries,
                    selected = form.shot,
                    label = { it.label },
                    onSelect = { shot ->
                        viewModel.updateImageForm { current -> current.copy(shot = shot) }
                    }
                )
                FieldLabel("НАСТРОЕНИЕ")
                ChoiceChips(
                    options = ImageMood.entries,
                    selected = form.mood,
                    label = { it.label },
                    onSelect = { mood ->
                        viewModel.updateImageForm { current -> current.copy(mood = mood) }
                    }
                )
            }
        }

        item {
            SectionCard(title = "Модель и формат", icon = Icons.Rounded.Tune) {
                FieldLabel("НЕЙРОСЕТЬ")
                ChoiceChips(
                    options = ImageTarget.entries,
                    selected = form.target,
                    label = { it.shortLabel },
                    onSelect = { target ->
                        viewModel.updateImageForm { current -> current.copy(target = target) }
                    }
                )
                FieldLabel("СООТНОШЕНИЕ СТОРОН")
                ChoiceChips(
                    options = ImageAspect.entries,
                    selected = form.aspect,
                    label = { it.label },
                    onSelect = { aspect ->
                        viewModel.updateImageForm { current -> current.copy(aspect = aspect) }
                    }
                )
                FieldLabel("ДЕТАЛИЗАЦИЯ")
                ChoiceChips(
                    options = listOf(true, false),
                    selected = form.highQuality,
                    label = { if (it) "Высокая" else "Базовая" },
                    onSelect = { quality ->
                        viewModel.updateImageForm { current ->
                            current.copy(highQuality = quality)
                        }
                    }
                )
                Text(
                    text = "Параметры модели подставляются в промт автоматически.",
                    style = MaterialTheme.typography.bodySmall,
                    color = MaterialTheme.colorScheme.onSurfaceVariant
                )
            }
        }

        item {
            SectionCard(title = "Negative prompt", icon = Icons.Rounded.Shield) {
                Text(
                    text = "Что модель не должна рисовать. Для Midjourney и DALL·E " +
                        "негатив не поддерживается — опишите запрет словами «without …».",
                    style = MaterialTheme.typography.bodySmall,
                    color = MaterialTheme.colorScheme.onSurfaceVariant
                )
                NegativeSuggestions(
                    onPick = { word ->
                        viewModel.updateImageForm { current ->
                            current.copy(negatives = appendNegative(current.negatives, word))
                        }
                    }
                )
                LabeledField(
                    label = "Исключить",
                    value = form.negatives,
                    onValueChange = { value ->
                        viewModel.updateImageForm { current -> current.copy(negatives = value) }
                    },
                    placeholder = "blurry, extra fingers, watermark, text",
                    minLines = 2,
                    maxLines = 4
                )
            }
        }

        item {
            ImagePreviewCard(
                form = form,
                english = generated.english,
                negative = generated.negative,
                parameters = generated.parameters,
                tokens = generated.tokens,
                score = generated.score,
                expanded = previewExpanded,
                onToggleExpanded = { previewExpanded = !previewExpanded },
                onCopy = {
                    context.copyToClipboard(generated.fullText)
                    viewModel.showMessage("Промт для изображения скопирован")
                },
                onShare = {
                    context.shareText(generated.fullText, subject = "Промт для изображения")
                },
                onSave = { showSaveDialog = true }
            )
        }
    }
}

